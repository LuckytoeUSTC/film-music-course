"""Organize OCR JSON into Markdown and archive the matching source images."""
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent
ARCHIVE = ROOT / "归档" / "Weixin图片"
PAGES = json.loads((ROOT / "weixin_ocr.json").read_text(encoding="utf-8"))

intro = """# 《电影艺术与音乐》图片资料整理

> 来源：42 张 Weixin 截图，对应原课件第 85–133 页（中间有缺页），按图片文件名顺序整理。以下提纲经过人工归类；附录保留逐图 OCR 结果，识别有误处应以原图为准。第 93 页有两张重复截图。

## 一、课程结构与进度

- 课程简介称分为三大部分：电影艺术及电影音乐概述、音乐基本理论、电影视听语言及要素。
- 目录涉及电影艺术、音乐艺术、电影音乐、电影视觉语言、电影组织体系和衍生商业模式；其中列有电影导演、电影配乐大师等内容。
- 第 1–2 周：课前准备，检视阅片量与电影音乐辨识（作业一）。
- 第 3–10 周：电影及电影音乐艺术。第 3 周讲心理机制与佳片欣赏；第 4–8 周讨论电影作品成功的主观因素（创作、制作）和客观因素（票房、评奖、评分，含作业二、三）；第 9–10 周讲电影音乐的性质、功能、运用、声画关系和结构类型（作业四）。
- 第 11–13 周：期末 PPT 讲演、分享与交流。

## 二、考核要求

### 形式一：PPT 讲演

- 自定题目或从推荐片单中选题；汇报前一周把内容发给老师，并把标题发到课程群。
- 约 10 组名额，第 7 周前报名并抽签；倒数第三周开始随堂讲演。
- 每组不超过 2 人，讲演不超过 45 分钟；课件写明以 A− 为基准分值。
- 需要设置互动环节，并提前在课程群发布大纲。高质量提问经老师评定可优化成绩。
- 课件注明三次未到无成绩。

### 形式二：课程论文

- 正文 5000–6000 字，不含摘要、关键词、参考文献。
- 结构建议：引言约 8%–10%；核心论点一、二各约 25%–30%；核心论点三约 20%–25%；结论约 8%–10%。原图中部分字数区间与百分比未必完全对应，写作时以总字数要求为主。
- 应有明确主题、2–3 个核心论点、3–4 个课程案例，以及能呼应主题的结论。无需强制设置文献综述或复杂理论模型。
- 课件以《冰雪奇缘》和《大鱼海棠》为例，强调比较民族音乐元素的运用方式，而非只列出使用了哪些民谣。
- 可参考老师片单选研究对象；课件另提附加作业 1–3 次和三次未到无成绩。

## 三、音乐与电影音乐基础

- **音乐的定义**：以有组织的声音（包括乐音及处理后的噪音）形成时间性的艺术形象，通过演唱或演奏、音响变化和作品结构表达情感与社会生活。
- **基本要素**：音高、时值、强弱、音色，以及节奏与节拍、旋律、和声／复调、调式调性、音区、力度、速度和织体。
- **电影的影响**：课件从艺术、文化、社会、经济四个领域举例，分别列《公民凯恩》《末代皇帝》《我不是药神》《哈利·波特》。
- **音乐与电影的关系**：音乐可放大情感、衔接叙事、延伸文化内涵；二者互相成就。课件列举《阿甘正传》《这个杀手不太冷》《闪灵》《星球大战》《盗梦空间》《卧虎藏龙》《芳华》《星际穿越》等。
- **音乐欣赏过程**：创作 → 表演 → 欣赏；欣赏可由音响感知，经过联想与想象，走向理解、认识和评价。电影音乐的体验从生理与环境层面的“情态”，发展到情绪唤起、情感共鸣和审美理解。

## 四、音乐欣赏中的“联觉”

- 课件将联觉解释为一种感觉引起其他感觉的心理现象，用巧克力、薄荷糖、音高、明暗、冷热和材质等作示例。
- 音乐本身没有直接的视觉形象或确定语义；听者仍可通过联觉、想象和情绪体验形成画面与理解。
- **视觉联想**：里姆斯基·科萨科夫《野蜂飞舞》与格里格《蝴蝶》；穆索尔斯基《莫斯科河上的黎明》用于讨论音高、时值如何表现黎明。
- **情绪与人物**：肖邦《葬礼进行曲》、民歌《小白菜》；《红色娘子军》中洪常青和南霸天的主题音乐。
- **概念与叙事**：西贝柳斯《芬兰颂》示意压迫、抗争、斗争与胜利的音乐表达。
- 小结：作曲家的表现意图，经由音乐与听者的联觉、情感和经验，形成理解与感受。

## 五、电影音乐的构成形态

| 类别 | 形态及用途 | 课件示例 |
| --- | --- | --- |
| 器乐／配乐 | 主题音乐、场景音乐、背景音乐；概括主题、推进情节、塑造环境与人物 | 《菊次郎的夏天》《魔戒》 |
| 歌曲 | 主题歌、插曲；直抒情感、点明主旨、增强记忆与传播 | 《哪吒之魔童闹海》（片名及歌名 OCR 有误，需核原图） |

## 六、逐图 OCR 文本

以下按原图编号排列，保留 OCR 原始措辞及其错误。原图链接可用于核对；图片中的流程图与表格被 OCR 拆成短行，需结合原图阅读。
"""

parts = [intro]
for page in PAGES:
    name = page["file"]
    parts += [f"\n### [{name}](归档/Weixin图片/{name.replace(' ', '%20')})\n"]
    parts += [f"- {line['text']}\n" for line in page["lines"]]

(ROOT / "电影艺术与音乐_图片资料整理.md").write_text("".join(parts), encoding="utf-8")
ARCHIVE.mkdir(parents=True, exist_ok=True)
for page in PAGES:
    src = ROOT / page["file"]
    dst = ARCHIVE / page["file"]
    if src.exists():
        if dst.exists():
            raise FileExistsError(dst)
        shutil.move(str(src), str(dst))
print(f"Wrote Markdown and archived {len(PAGES)} images in {ARCHIVE}")
